-- Stati del mondo con capitale e livello di difficoltà (1 = facilissimo, 5 = difficilissimo).
-- "aliases" contiene risposte alternative accettate, separate da "|".
CREATE TABLE IF NOT EXISTS countries (
    id INTEGER PRIMARY KEY NOT NULL,
    name TEXT NOT NULL UNIQUE,
    capital TEXT NOT NULL,
    aliases TEXT NOT NULL DEFAULT '',
    tier INTEGER NOT NULL CHECK (tier BETWEEN 1 AND 5),
    continent TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS countries_tier ON countries (tier);

CREATE TABLE IF NOT EXISTS scores (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    player TEXT NOT NULL,
    score INTEGER NOT NULL,
    level INTEGER NOT NULL,
    correct INTEGER NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS scores_score ON scores (score DESC);

